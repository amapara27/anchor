import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

export async function terminalWorkflows({ terminal, scratch, run, requests, models, setStream, checkpoint }) {
    const ui = terminal();
    const slash = async name => {
        ui.send('/' + name);
        await ui.waitScreen('┌ Commands ');
        ui.send('\r');
        if (name !== 'quit') await ui.waitGone('┌ Commands ');
    };
    const button = index => ui.send('\t'.repeat(index + 1) + '\r');
    await ui.waitScreen('Models  1/');
    ui.send('fixture:1b\r');
    await ui.waitScreen('Selected fixture:1b');
    checkpoint('terminal-benchmark-and-background-navigation');
    setStream(true);
    await slash('bench');
    await ui.waitScreen('Run benchmark');
    ui.send('\t\r');
    await ui.waitScreen('Choose Workload');
    ui.send('classify\r');
    await ui.waitScreen('Workload: classify');
    ui.send('\t\t\r');
    await ui.waitScreen('chunks/s');
    await slash('models');
    await ui.waitScreen('Models  1/');
    assert(ui.screen.includes('Ctrl-C stop'), 'job remains visible across navigation');
    await ui.waitScreen('Completed Run benchmark');
    setStream(false);
    assert(requests.some(r => r.route === '/api/generate' && r.body.model === 'fixture:1b'));
    checkpoint('terminal-results-reports-export-and-replay');
    await slash('results');
    await ui.waitScreen('saved measurements');
    button(0);
    await ui.waitScreen('Measured workloads');
    await ui.waitScreen('TTFT');
    button(1);
    await ui.waitScreen('Repeat samples');
    await ui.waitScreen('decode_tps');
    await ui.escape();
    await ui.waitScreen('Measured workloads');
    button(0);
    await ui.waitScreen('Measurement report');
    await ui.waitScreen('Formula: 2');
    await ui.escape();
    await ui.waitScreen('Measured workloads');
    button(2);
    await ui.waitScreen('Export evidence');
    const exported = path.join(scratch, 'terminal-evidence.json');
    ui.send('\x15' + exported + '\t\r');
    await ui.waitScreen('Evidence saved to');
    const evidence = JSON.parse(await readFile(exported, 'utf8'));
    assert(evidence.session && evidence.attempts.length > 0);
    await slash('replay');
    await ui.waitScreen('Replay evidence offline');
    ui.send(exported + '\t\r');
    await ui.waitScreen('Completed Replay evidence offline');
    await slash('leaderboard');
    await ui.waitScreen('Leaderboard workload');
    ui.send('\t\r');
    await ui.waitScreen('Runtime-reported rates');
    await ui.capture('terminal-leaderboard');
    checkpoint('terminal-chat-streaming-history-and-presets');
    await slash('chat');
    await ui.waitScreen('Send message');
    ui.send('\tHello terminal 🌍\t\r');
    await ui.waitScreen('Fixture answer');
    await ui.waitScreen('Conversation');
    const conversations = await run(['chat', 'ls', '--json'], { json: true });
    const saved = conversations.find(c => c.title === 'Hello terminal 🌍');
    assert(saved);
    assert.equal((await run(['chat', 'show', saved.id, '--json'], { json: true })).length, 2);
    await slash('history');
    await ui.waitScreen('Hello terminal 🌍');
    ui.send('Hello terminal\r');
    await ui.waitScreen('Conversation');
    button(0);
    await ui.waitScreen('Send message');
    ui.send('\tFollow-up\t\r');
    await ui.waitScreen('Fixture answer');
    await ui.waitScreen('Conversation');
    assert.equal((await run(['chat', 'show', saved.id, '--json'], { json: true })).length, 4);
    await slash('presets');
    await ui.waitScreen('Inference presets');
    button(1);
    await ui.waitScreen('Save inference preset');
    ui.send('terminal-preset\t-- Terminal preset\t-- Use terminal fixture\t0.2\t0.8\t2048\t\t\r');
    await ui.waitScreen('Completed Save inference preset');
    const preset = (await run(['settings', 'presets', 'ls', '--json'], { json: true })).find(p => p.id === 'terminal-preset');
    assert.equal(preset.name, '-- Terminal preset');
    assert.equal(preset.system, '-- Use terminal fixture');
    assert.equal(preset.num_ctx, 2048);
    checkpoint('terminal-settings-fit-compare-and-confirmations');
    await slash('settings');
    await ui.waitScreen('Server status');
    ui.send('\x1b[F\r');
    await ui.waitScreen('Resident models');
    await ui.escape();
    await ui.waitScreen('Server status');
    ui.send('Paths\r');
    await ui.waitScreen('registry');
    await slash('fit');
    await ui.waitScreen('Estimate memory');
    ui.send('\t\x150\t\t\r');
    await ui.waitScreen('context length must be greater than zero');
    // Validation failure is visible; navigation and another operation still work.
    await slash('fit');
    await ui.waitScreen('Estimate memory');
    ui.send('\t\t\t\r');
    await ui.waitScreen('Completed Estimate memory');
    await slash('compare');
    await ui.waitScreen('Compare models');
    ui.send('\t\tCompare fixture\t\r');
    await ui.waitScreen('Completed Compare models');
    await slash('models');
    await ui.waitScreen('Models  1/');
    await ui.waitScreen('Models  1/' + models.length);
    ui.send('picker:000');
    await ui.waitScreen('Models  1/1');
    button(7);
    await ui.waitScreen('Model files will be deleted');
    ui.send('\r');
    await ui.waitScreen('Cancelled; nothing changed');
    assert(models.some(m => m.name === 'picker:000'));
    button(7);
    await ui.waitScreen('Model files will be deleted');
    ui.send('\x1b[C\r');
    await ui.waitScreen('Completed Confirmed action');
    assert(!models.some(m => m.name === 'picker:000'));
    const orphan = path.join(scratch, 'models/blobs', 'sha256-' + 'b'.repeat(64));
    await writeFile(orphan, 'terminal orphan');
    await slash('storage');
    await ui.waitScreen('orphaned_bytes');
    button(0);
    await ui.waitScreen('freeing 15 B');
    ui.send('\r');
    await ui.waitScreen('Cancelled; nothing changed');
    assert.equal(await readFile(orphan, 'utf8'), 'terminal orphan');
    // Reopen resets action focus, then confirm cleanup through the real backend.
    await slash('storage');
    await ui.waitScreen('orphaned_bytes');
    button(0);
    await ui.waitScreen('freeing 15 B');
    ui.send('\x1b[C\r');
    await ui.waitScreen('Completed Confirmed action');
    assert.equal((await run(['storage', 'scan', '--json'], { json: true })).orphaned_bytes, 0);
    await ui.capture('terminal-workspace');
    await slash('quit');
    await ui.finish();
}
