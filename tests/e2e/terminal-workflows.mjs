import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

export async function terminalWorkflows({ terminal, scratch, run, requests, models, setStream, checkpoint }) {
    const ui = terminal();
    const slash = async name => {
        ui.send('/' + name);
        await ui.waitScreen('Slash commands');
        ui.send('\r');
        if (name !== 'quit') await ui.waitGone('Slash commands');
    };
    const button = index => ui.send('\t'.repeat(index + 1) + '\r');
    await ui.waitScreen('Type / for commands');
    const version = (await run(['--version'])).trim().split(' ').at(-1);
    ui.resize(60, 110);
    await ui.waitScreen('Type / for commands');
    const home = ui.screen.split('\n');
    const logo = screen => screen.split('\n').slice(0, 5).map(line => line.slice(0, 12).trimEnd());
    assert(home[0].includes('Anchor v' + version) && home[4].includes('▀▀▄▄█▄▄▀▀'));
    assert(home.findIndex(line => line.includes('Type / for commands')) >= 57);
    assert.doesNotMatch(ui.screen, /Choose a local model|Run a benchmark|Browse measurements/);
    await ui.capture('terminal-home-tall');
    ui.resize(18, 40);
    await ui.waitScreen('Type / for commands');
    assert.deepEqual(logo(ui.screen), logo(home.join('\n')));
    ui.send('/');
    await ui.waitScreen('Slash commands');
    const menu = ui.screen.split('\n');
    assert(menu.findIndex(line => line.includes('Slash commands')) >= 8);
    assert(menu.findIndex(line => line.trim() === '› /') >= 15);
    await ui.capture('terminal-home-narrow-commands');
    await ui.escape();
    ui.resize(30, 100);
    await ui.waitScreen('Type / for commands');
    await slash('bench');
    await ui.waitScreen('Choose a model  1/');
    ui.send('fixture:1b\r');
    checkpoint('terminal-benchmark-and-background-navigation');
    setStream(true);
    await ui.waitScreen('Run benchmark');
    await ui.waitScreen('Model: fixture:1b');
    assert(!ui.screen.includes('Type to filter'));
    ui.resize(16, 50);
    await ui.waitScreen('Tab / ↑↓ fields · Esc back');
    await ui.capture('terminal-bench-form-50');
    ui.send('\t\r');
    await ui.waitScreen('Choose Workload');
    await ui.escape();
    await ui.waitScreen('Workload: all nine');
    ui.send('\r');
    await ui.waitScreen('Choose Workload');
    ui.send('classify\r');
    await ui.waitScreen('Workload: classify');
    await ui.escape();
    await ui.waitScreen('Type / for commands');
    await slash('bench');
    await ui.waitScreen('Workload: classify');
    ui.resize(30, 100);
    await ui.waitScreen('Workload: classify');
    ui.send('\t');
    ui.send('\t\t\r');
    await ui.waitScreen('chunks/s');
    assert.deepEqual(logo(ui.screen), logo(home.join('\n')), 'benchmarks retain the Home mark');
    await ui.capture('terminal-bench-mark');
    await slash('models');
    await ui.waitScreen('Installed  1/');
    assert(ui.screen.includes('Ctrl-C stop'), 'job remains visible across navigation');
    await ui.waitScreen('Completed Run benchmark');
    setStream(false);
    assert(requests.some(r => r.route === '/api/generate' && r.body.model === 'fixture:1b'));
    await slash('activity');
    await ui.waitScreen('1 workload measured · Ollama');
    await ui.waitScreen('Post-first-token decode');
    await ui.waitScreen('classify complete');
    await ui.capture('terminal-benchmark-summary');
    checkpoint('terminal-results-reports-export-and-replay');
    await slash('results');
    await ui.waitScreen('last measured');
    button(0);
    await ui.waitScreen('Measured workloads');
    await ui.waitScreen('TTFT ms');
    await ui.waitScreen('9 workloads');
    assert.match(ui.screen, /Run 1.*1 workload/);
    assert.equal(ui.screen.split('\n').filter(line => line.includes('fixture:1b')).length, 2, 'one active-model label and one table label');
    ui.send('\x1b[B');
    await ui.waitScreen('Measured workloads  2/');
    assert.match(ui.screen, /› classify/);
    ui.send('\x1b[F');
    await ui.waitScreen('Legacy · anchor-scenarios v4');
    ui.send('\r');
    await ui.waitScreen('Workload summary');
    await ui.waitScreen('short · 1024 ctx');
    await ui.escape();
    await ui.waitScreen('Measured workloads');
    ui.send('\x1b[H');
    await ui.waitScreen('Measured workloads  1/');
    await ui.capture('terminal-grouped-workloads-100');
    ui.resize(18, 50);
    await ui.waitScreen('TTFT ms');
    assert.match(ui.screen, /› classify\s+1024\s+N\/A\s+\d+\.\d$/m);
    await ui.capture('terminal-grouped-workloads-50');
    button(1);
    await ui.waitScreen('Repeat samples');
    await ui.waitScreen('Repeat 1 · prefill');
    assert.doesNotMatch(ui.screen, /"decode_tps"|\bnull\b/);
    await ui.capture('terminal-repeat-samples-50');
    await ui.escape();
    await ui.waitScreen('Measured workloads');
    button(0);
    await ui.waitScreen('Measurement report');
    await ui.waitScreen('classify · 3/3 repeats');
    await ui.waitScreen('decode N/A');
    assert.doesNotMatch(ui.screen, /"attempts"|"scenarios"|"decode_tps_median"/);
    await ui.capture('terminal-saved-report-50');
    ui.resize(30, 100);
    await ui.waitScreen('Formula: 2');
    await ui.capture('terminal-saved-report-100');
    await ui.escape();
    await ui.waitScreen('Measured workloads');
    button(3);
    await ui.waitScreen('Workload summary');
    await ui.waitScreen('Median measurements');
    await ui.waitScreen('1024 ctx');
    assert.doesNotMatch(ui.screen, /"decode_tps_median"/);
    await ui.escape();
    await ui.waitScreen('Measured workloads');
    button(2);
    await ui.waitScreen('Export evidence');
    const exported = path.join(scratch, 'terminal-evidence.json');
    ui.send('\x15' + exported + '\t\r');
    await ui.waitScreen('Evidence saved to');
    const evidence = JSON.parse(await readFile(exported, 'utf8'));
    assert(evidence.session && evidence.attempts.length > 0);
    await slash('replay');
    await ui.waitScreen('Replay evidence offline');
    ui.send(exported + '\t\r');
    await ui.waitScreen('Completed Replay evidence offline');
    await ui.waitScreen('classify · 3/3 repeats');
    assert.doesNotMatch(ui.screen, /"attempts"|"scenarios"/);
    await slash('leaderboard');
    await ui.waitScreen('Leaderboard workload');
    ui.send('\t\r');
    await ui.waitScreen('Runtime-reported rates');
    await ui.capture('terminal-leaderboard');
    checkpoint('terminal-chat-streaming-history-and-presets');
    await slash('chat');
    await ui.waitScreen('Send message');
    ui.send('\tHello terminal 🌍\t\r');
    await ui.waitScreen('Fixture answer');
    await ui.waitScreen('Conversation');
    await ui.waitScreen('Completed Send message');
    const conversations = await run(['chat', 'ls', '--json'], { json: true });
    const saved = conversations.find(c => c.title === 'Hello terminal 🌍');
    assert(saved);
    assert.equal((await run(['chat', 'show', saved.id, '--json'], { json: true })).length, 2);
    await slash('history');
    await ui.waitScreen('Hello terminal 🌍');
    ui.send('Hello terminal\r');
    await ui.waitScreen('Conversation');
    await ui.waitScreen('Fixture answer');
    button(0);
    await ui.waitScreen('Send message');
    ui.send('\tFollow-up\t\r');
    await ui.waitScreen('› Follow-up\n\n Fixture reasoning\n Fixture answer');
    await ui.waitScreen('Completed Send message');
    assert.equal((await run(['chat', 'show', saved.id, '--json'], { json: true })).length, 4);
    // Typing in a conversation replies inline through the same chat command.
    ui.send('Inline reply check');
    await ui.waitScreen('› Inline reply check');
    ui.send('\r');
    await ui.waitScreen('› Inline reply check\n\n Fixture reasoning\n Fixture answer');
    await ui.waitScreen('Completed Send message');
    const inline = await run(['chat', 'show', saved.id, '--json'], { json: true });
    assert.equal(inline.length, 6);
    assert.equal(inline.at(-2).content, 'Inline reply check');
    assert.equal(inline.at(-1).content, 'Fixture answer');
    await slash('presets');
    await ui.waitScreen('Inference presets');
    await ui.waitScreen('Inference presets  1/');
    button(1);
    await ui.waitScreen('Save inference preset');
    ui.send('terminal-preset\t-- Terminal preset\t-- Use terminal fixture\t0.2\t0.8\t2048\t\t\r');
    await ui.waitScreen('Completed Save inference preset');
    const preset = (await run(['settings', 'presets', 'ls', '--json'], { json: true })).find(p => p.id === 'terminal-preset');
    assert.equal(preset.name, '-- Terminal preset');
    assert.equal(preset.system, '-- Use terminal fixture');
    assert.equal(preset.num_ctx, 2048);
    checkpoint('terminal-settings-fit-compare-and-confirmations');
    await slash('settings');
    await ui.waitScreen('Server status');
    ui.send('\x1b[F\r');
    await ui.waitScreen('Resident models');
    await ui.escape();
    await ui.waitScreen('Server status');
    ui.send('Paths\r');
    await ui.waitScreen('registry');
    await slash('fit');
    await ui.waitScreen('Estimate memory');
    ui.send('\t\x150\t\t\r');
    await ui.waitScreen('context length must be greater than zero');
    // Validation failure is visible; navigation and another operation still work.
    await slash('fit');
    await ui.waitScreen('Estimate memory');
    ui.send('\t\t\t\r');
    await ui.waitScreen('Completed Estimate memory');
    await slash('compare');
    await ui.waitScreen('Compare models');
    ui.send('\t\tCompare fixture\t\r');
    await ui.waitScreen('Completed Compare models');
    await slash('models');
    await ui.waitScreen('Installed  1/');
    await ui.waitScreen('Installed  1/' + models.length);
    ui.send('picker:000');
    await ui.waitScreen('Installed  1/1');
    button(7);
    await ui.waitScreen('Model files will be deleted');
    ui.send('\r');
    await ui.waitScreen('Cancelled; nothing changed');
    assert(models.some(m => m.name === 'picker:000'));
    button(7);
    await ui.waitScreen('Model files will be deleted');
    ui.send('\x1b[C\r');
    await ui.waitScreen('Completed Confirmed action');
    assert(!models.some(m => m.name === 'picker:000'));
    const orphan = path.join(scratch, 'models/blobs', 'sha256-' + 'b'.repeat(64));
    await writeFile(orphan, 'terminal orphan');
    await slash('storage');
    await ui.waitScreen('Orphaned');
    button(0);
    await ui.waitScreen('freeing 15 B');
    ui.send('\r');
    await ui.waitScreen('Cancelled; nothing changed');
    assert.equal(await readFile(orphan, 'utf8'), 'terminal orphan');
    // Reopen resets action focus, then confirm cleanup through the real backend.
    await slash('storage');
    await ui.waitScreen('Orphaned');
    button(0);
    await ui.waitScreen('freeing 15 B');
    ui.send('y'); // the confirmation's keyboard shortcut accepts directly
    await ui.waitScreen('Completed Confirmed action');
    assert.equal((await run(['storage', 'scan', '--json'], { json: true })).orphaned_bytes, 0);
    await ui.capture('terminal-workspace');
    await slash('quit');
    await ui.finish();
}
