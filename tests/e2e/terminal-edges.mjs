import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import path from 'node:path';

export async function terminalEdges({ terminal, scratch, run, models, requests, setStream, setOffline, setAnswer, checkpoint }) {
    const ui = terminal();
    const slash = async name => {
        ui.send('/' + name); await ui.waitScreen('┌ Commands '); ui.send('\r');
        if (name !== 'quit') await ui.waitGone('┌ Commands ');
    };
    const button = index => ui.send('\t'.repeat(index + 1) + '\r');
    await ui.waitScreen('Models  1/');
    ui.send('fixture:1b\r'); await ui.waitScreen('Selected fixture:1b');
    checkpoint('terminal-drafts-editing-and-multiline-paste');
    await slash('chat'); await ui.waitScreen('Send message');
    ui.send('\tDraft αβ\x1b[D!'); await ui.waitScreen('Draft α!β');
    await ui.escape();
    await slash('settings'); await ui.waitScreen('Server status');
    await slash('chat'); await ui.waitScreen('Draft α!β');
    ui.send('\t\x15\x1b[200~Line one\nLine two 🌍\x1b[201~\t\r');
    await ui.waitScreen('Conversation'); await ui.waitScreen('Fixture answer');
    const chats = await run(['chat', 'ls', '--json'], { json: true });
    const multi = chats.find(c => c.title.startsWith('Line one'));
    assert(multi);
    const saved = await run(['chat', 'show', multi.id, '--json'], { json: true });
    assert.equal(saved[0].content, 'Line one\nLine two 🌍');
    assert(requests.some(r => r.route === '/api/chat' && r.body.messages.at(-1).content === saved[0].content));
    checkpoint('terminal-preset-edit-clear-assign-and-regenerate');
    await slash('presets'); await ui.waitScreen('Inference presets');
    ui.send('terminal-preset\r'); await ui.waitScreen('Save inference preset');
    ui.send('\t\x15Edited preset\t\x15\t\t\t\t\t\r');
    await ui.waitScreen('Completed Save inference preset');
    const preset = (await run(['settings', 'presets', 'ls', '--json'], { json: true })).find(p => p.id === 'terminal-preset');
    assert.equal(preset.name, 'Edited preset'); assert.equal(preset.system, null);
    await slash('history'); await ui.waitScreen('Conversations');
    ui.send('Line one\r'); await ui.waitScreen('Conversation'); await ui.waitScreen('Fixture answer');
    button(2); await ui.waitScreen('Conversation preset');
    ui.send('\r'); await ui.waitScreen('Choose Preset');
    ui.send('terminal-preset\r'); await ui.waitScreen('Preset: terminal-preset');
    ui.send('\t\r'); await ui.waitScreen('Completed Conversation preset');
    assert.equal((await run(['chat', 'ls', '--json'], { json: true })).find(c => c.id === multi.id).preset_id, 'terminal-preset');
    button(0); await ui.waitScreen('Send message');
    ui.send('\tPreset wire check\t\r'); await ui.waitScreen('Conversation'); await ui.waitScreen('Fixture answer');
    const wire = requests.filter(r => r.route === '/api/chat').at(-1).body;
    assert.equal(wire.options.num_ctx, 2048); assert.equal(wire.options.temperature, Math.fround(0.2)); assert.equal(wire.options.top_p, Math.fround(0.8));
    button(1); await ui.waitScreen('Regenerate reply'); await ui.waitScreen('Conversation'); await ui.waitScreen('Fixture answer');
    assert.equal((await run(['chat', 'show', multi.id, '--json'], { json: true })).length, 4);
    checkpoint('terminal-chat-stop-and-quit-confirmation');
    setStream(true);
    button(0); await ui.waitScreen('Send message');
    ui.send('\tStop this reply\t\r'); await ui.waitScreen('Fixture answer');
    ui.send('\x03'); await ui.waitScreen('Stopped;');
    const partial = await run(['chat', 'show', multi.id, '--json'], { json: true });
    assert.equal(partial.at(-1).content, 'Fixture answer');
    assert.equal(partial.length, 6);
    await slash('bench'); await ui.waitScreen('Run benchmark');
    ui.send('\t\t\t\r'); await ui.waitScreen('chunks/s');
    await slash('quit'); await ui.waitScreen('Stop the running job and quit?');
    ui.send('\r'); await ui.waitScreen('Cancelled; nothing changed');
    assert(ui.screen.includes('Ctrl-C stop'));
    ui.send('\x03'); await ui.waitScreen('Stopped;');
    setStream(false);
    const sessions = await run(['bench', 'sessions', '--json'], { json: true });
    assert(sessions.some(s => s.outcome === 'cancelled'));
    checkpoint('terminal-offline-recovery-and-wrapped-text');
    setOffline(true);
    await slash('models'); await ui.waitScreen('Models  1/'); await ui.waitScreen('Ready');
    await slash('settings'); await ui.waitScreen('Server status'); ui.send('\r');
    await ui.waitScreen('"reachable": false');
    setOffline(false);
    ui.send('\x0c'); await ui.waitScreen('"reachable": true');
    setAnswer('wrapped reply '.repeat(300) + 'WRAP-END');
    const long = await run(['chat', '-m', 'fixture:1b', 'Long terminal reply', '--json'], { json: true });
    assert(long.conversation_id); setAnswer('Fixture answer');
    await slash('history'); await ui.waitScreen('Conversations');
    ui.send('Long terminal reply\r'); await ui.waitScreen('Conversation'); await ui.waitScreen('wrapped reply');
    ui.resize(16, 50); await ui.waitScreen('Conversation');
    ui.send('\x1b[F'); await ui.waitScreen('WRAP-END');
    await ui.capture('terminal-wrapped-50');
    ui.resize(8, 30); await ui.waitScreen('Enlarge to 36');
    ui.resize(30, 100); await ui.waitScreen('Conversation');
    checkpoint('terminal-leading-dash-rename');
    await slash('history'); await ui.waitScreen('Conversations');
    ui.send('Long terminal reply'); await ui.waitScreen('Conversations  1/1');
    button(1); await ui.waitScreen('Rename conversation');
    ui.send('\x15-- renamed terminal\t\r');
    await ui.waitScreen('Completed Rename conversation');
    assert.equal((await run(['chat', 'ls', '--json'], { json: true })).find(c => c.id === long.conversation_id).title, '-- renamed terminal');
    checkpoint('terminal-safe-export-collision');
    await slash('sessions'); await ui.waitScreen('Run history');
    await ui.waitScreen('completed');
    button(2); await ui.waitScreen('Export evidence');
    const file = path.join(scratch, 'terminal-evidence.json'), before = await readFile(file, 'utf8');
    ui.send('\x15' + file + '\t\r');
    await ui.waitScreen('existing files are never overwritten');
    assert.equal(await readFile(file, 'utf8'), before);
    await ui.escape();
    await slash('quit'); await ui.finish();
    checkpoint('terminal-signal-restoration');
    const signal = terminal();
    await signal.waitScreen('Models  1/');
    signal.child.kill('SIGTERM');
    await signal.finish();
    assert(models.some(m => m.name === 'fixture:1b'));
}
